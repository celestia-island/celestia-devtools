def test_cast_never_is_source_only(tmp_path):
    write(tmp_path, "src/real.ts", "export const a = b as never;\n")
    write(tmp_path, "tests/guard.test.ts", "export const c = check(null as never);\n")
    assert type_escapes.main([str(tmp_path)]) == 1
    assert type_escapes.main([str(tmp_path / "tests")]) == 0

def test_strict_ruleset_adds_the_erasures_core_leaves_alone(tmp_path):
    body = "export const a = JSON.parse(raw);\nexport const b: Function = handler;\nexport const c = (event.target as HTMLElement).id;\n"
    write(tmp_path, "strict.ts", body)
    assert type_escapes.main([str(tmp_path)]) == 0
    assert type_escapes.main([str(tmp_path), "--ruleset", "strict"]) == 1

def test_counted_assertions_are_counted_but_do_not_fail(tmp_path):
    write(tmp_path, "debt.ts", "export const el = document.querySelector(\"#app\")!;\nexport const card = body as HTMLElement;\n")
    assert type_escapes.main([str(tmp_path)]) == 0
    assert type_escapes.main([str(tmp_path), "--json"]) == 0

def test_inventory_counts_by_rule_and_profile(tmp_path, capsys):
    write(tmp_path, "src/one.ts", "export const card = body as HTMLElement;\n")
    write(tmp_path, "tests/two.test.ts", "export const el = node!;\n")
    assert type_escapes.main([str(tmp_path), "--inventory", "--json"]) == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["rules"]["as-assert"]["profiles"] == {"src": 1}
    assert payload["rules"]["nonnull-assert"]["profiles"] == {"test": 1}

def test_ratchet_refuses_growth_and_accepts_a_recorded_baseline(tmp_path, capsys):
    body = "export const card = body as HTMLElement;\n"
    write(tmp_path, "debt.ts", body)
    baseline = tmp_path / "baseline.json"
    assert type_escapes.main([str(tmp_path), "--update-baseline", str(baseline)]) == 0
    assert type_escapes.main([str(tmp_path), "--baseline", str(baseline)]) == 0
    write(tmp_path, "debt.ts", body + "export const other = node as HTMLElement;\n")
    assert type_escapes.main([str(tmp_path), "--baseline", str(baseline)]) == 1
    assert "ratchet" in capsys.readouterr().out

def test_ratchet_refuses_new_files_until_told_otherwise(tmp_path):
    write(tmp_path, "debt.ts", "export const card = body as HTMLElement;\n")
    baseline = tmp_path / "baseline.json"
    assert type_escapes.main([str(tmp_path), "--update-baseline", str(baseline)]) == 0
    write(tmp_path, "new.ts", "export const extra = node as HTMLElement;\n")
    assert type_escapes.main([str(tmp_path), "--baseline", str(baseline)]) == 1
    assert type_escapes.main([str(tmp_path), "--baseline", str(baseline), "--baseline-allow-new"]) == 0

def test_dmts_and_dcts_are_declaration_files(tmp_path):
    write(tmp_path, "plugin.d.mts", "declare const payload: any;\n")
    write(tmp_path, "plugin.d.cts", "declare const other: any;\n")
    hits = type_escapes.scan_text("declare const payload: any;\n", "plugin.d.mts")
    assert hits and (hits[0]["profile"] == type_escapes.PROFILE_DTS)
    assert type_escapes.main([str(tmp_path)]) == 0
    assert type_escapes.main([str(tmp_path), "--fail-on-dts"]) == 1

def test_unreadable_baseline_is_a_usage_error(tmp_path):
    write(tmp_path, "debt.ts", "export const card = body as HTMLElement;\n")
    broken = tmp_path / "broken.json"
    broken.write_text("{not json", encoding = "utf-8")
    assert type_escapes.main([str(tmp_path), "--baseline", str(broken)]) == 2
